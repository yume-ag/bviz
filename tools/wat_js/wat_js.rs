//! Compiles WebAssembly text modules into a JavaScript module that exports each
//! one's binary as a `Uint8Array` constant.

use std::fs::File;
use std::io::{self, BufWriter, Write};

const USAGE: &str = "usage: wat_js <output.js> <NAME=input.wat>...";

fn main() -> io::Result<()> {
    let mut args = std::env::args().skip(1);
    let output = args.next().unwrap_or_else(|| panic!("{USAGE}"));
    let mut out = BufWriter::new(File::create(output)?);
    writeln!(out, "// @generated by wat_js.")?;
    for arg in args {
        let (name, path) = arg.split_once('=').unwrap_or_else(|| panic!("{USAGE}"));
        let binary = wat::parse_file(path).unwrap_or_else(|error| panic!("{error}"));
        write_export(&mut out, name, &binary)?;
    }
    out.flush()
}

fn write_export(out: &mut impl Write, name: &str, binary: &[u8]) -> io::Result<()> {
    write!(out, "export const {name} = new Uint8Array([")?;
    for (index, byte) in binary.iter().enumerate() {
        let separator = if index == 0 { "" } else { ", " };
        write!(out, "{separator}0x{byte:02x}")?;
    }
    writeln!(out, "]);")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exports_a_compiled_module() {
        let binary = wat::parse_str("(module)").unwrap();
        let mut out = Vec::new();
        write_export(&mut out, "EMPTY", &binary).unwrap();
        assert_eq!(
            String::from_utf8(out).unwrap(),
            "export const EMPTY = new Uint8Array([0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00]);\n",
        );
    }
}
